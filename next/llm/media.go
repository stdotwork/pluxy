package llm

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"mime"
	"strings"
)

// Output media kinds (protocol minor version 33).
const (
	MediaImage = "image"
	MediaAudio = "audio"
)

// MaxOutputMediaPartBytes is the largest base64 Data string a single media event carries.
// Keeping each part at or below 24 MiB ensures that even when Event.Raw carries the same
// upstream chunk alongside Event.Media, the serialized JSON event fits inside
// protocol.MaxFrame (64 MiB).
const MaxOutputMediaPartBytes = 24 << 20

// MaxOutputMediaReplyBytes is the total base64 Data bytes a single reply carries across all
// media events. Parts beyond this limit are dropped with a reported loss instead of failing the
// reply. It is larger than protocol.MaxFrame so a reply with several media parts can stream
// across separate frames without hitting a single-frame ceiling.
const MaxOutputMediaReplyBytes = 96 << 20

// MaxNonStreamedReplyBytes is the most core collects for a reply it sends whole. An aggregator
// that holds media leaves out the parts that do not fit, with a loss, and core fails the reply
// only for what it cannot leave out.
const MaxNonStreamedReplyBytes = 64 << 20

// OutputMedia is one image or audio part generated by the model in a reply (protocol minor
// version 33). It carries only what more than one format can express: its kind (image or audio),
// its MIME media type (an allowlisted image or audio type, never image/svg+xml), and its base64-encoded bytes.
type OutputMedia struct {
	Kind      string `json:"kind"`
	MediaType string `json:"media_type"`
	Data      string `json:"data"`
}

// outputImageTypes and outputAudioTypes are the media types a reply may carry as generated
// media. A type not listed is not understood and is refused, so a type that only looks safe
// (an SVG in disguise, an unknown vendor type) never reaches a client that builds a data URL
// from it.
var (
	outputImageTypes = map[string]bool{
		"image/png": true, "image/jpeg": true, "image/jpg": true, "image/gif": true,
		"image/webp": true, "image/avif": true, "image/heic": true, "image/heif": true,
		"image/bmp": true, "image/tiff": true,
	}
	outputAudioTypes = map[string]bool{
		"audio/wav": true, "audio/x-wav": true, "audio/wave": true, "audio/vnd.wave": true,
		"audio/mpeg": true, "audio/mp3": true, "audio/mp4": true, "audio/m4a": true, "audio/x-m4a": true,
		"audio/aac": true, "audio/ogg": true, "audio/opus": true, "audio/webm": true,
		"audio/flac": true, "audio/x-flac": true, "audio/aiff": true, "audio/x-aiff": true,
		"audio/basic": true, "audio/pcm": true, "audio/l16": true, "audio/mulaw": true, "audio/alaw": true,
	}
)

// MediaBaseType returns the lower-cased type/subtype of mediaType, parsed strictly (RFC 2045
// tokens, then optional well-formed parameters) after surrounding whitespace is trimmed. ok is
// false when mediaType is not exactly a media type: trailing text, a comma, an empty part or a
// malformed parameter all fail, so nothing after the subtype can be hidden from a comparison.
func MediaBaseType(mediaType string) (base string, ok bool) {
	base, _, err := mime.ParseMediaType(strings.TrimSpace(mediaType))
	if err != nil || base == "" {
		return "", false
	}
	return base, true
}

// SafeOutputMediaKind checks whether mediaType is an output image or audio media type this
// package understands. Only the listed types pass, so image/svg+xml, which can carry script, and
// anything unrecognised are refused. Returns the canonical kind (MediaImage or MediaAudio) or a
// short reason suitable for a loss detail (never containing media bytes).
func SafeOutputMediaKind(mediaType string) (kind, problem string) {
	if strings.TrimSpace(mediaType) == "" {
		return "", "missing media type"
	}
	base, ok := MediaBaseType(mediaType)
	if !ok {
		return "", "invalid media type"
	}
	switch {
	case base == "image/svg+xml":
		return "", "image/svg+xml is not carried"
	case outputImageTypes[base]:
		return MediaImage, ""
	case outputAudioTypes[base]:
		return MediaAudio, ""
	}
	return "", "unsupported output media type"
}

// Base64Valid reports whether s is non-empty standard base64 (padded or unpadded, ignoring CR/LF
// MIME wrapping) without decoding or copying the bytes.
func Base64Valid(s string) bool {
	chars := 0
	pad := 0
	padded := false
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '\r' || c == '\n':
			continue
		case c == '=':
			pad++
			padded = true
		case padded:
			return false
		case c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '+' || c == '/':
			chars++
		default:
			return false
		}
	}
	if chars == 0 || pad > 2 {
		return false
	}
	if padded {
		return (chars+pad)%4 == 0 && ((chars%4 == 2 && pad == 2) || (chars%4 == 3 && pad == 1))
	}
	return chars%4 != 1
}

// ValidOutputMedia validates a protocol 0.33 OutputMedia record: non-nil, allowlisted image or
// audio media type (never image/svg+xml) matching Kind, non-empty valid base64, and within
// MaxOutputMediaPartBytes. Error messages never include media bytes.
func ValidOutputMedia(m *OutputMedia) error {
	if m == nil {
		return fmt.Errorf("missing output media")
	}
	kind, problem := SafeOutputMediaKind(m.MediaType)
	if problem != "" {
		return fmt.Errorf("%s", problem)
	}
	if m.Kind != kind {
		return fmt.Errorf("media kind %q does not match media type", m.Kind)
	}
	if len(m.Data) == 0 {
		return fmt.Errorf("empty output media data")
	}
	if len(m.Data) > MaxOutputMediaPartBytes {
		return fmt.Errorf("output media part exceeds %d bytes", MaxOutputMediaPartBytes)
	}
	if !Base64Valid(m.Data) {
		return fmt.Errorf("invalid base64 data")
	}
	return nil
}

// decodeBase64Prefix decodes up to 18 leading bytes from b64 into a stack buffer without copying
// the whole string, for magic-byte sniffing.
func decodeBase64Prefix(b64 string) []byte {
	var clean [24]byte
	n := 0
	for i := 0; i < len(b64) && n < len(clean); i++ {
		c := b64[i]
		if c == '\r' || c == '\n' {
			continue
		}
		clean[n] = c
		n++
	}
	n -= n % 4
	if n == 0 {
		return nil
	}
	var out [18]byte
	m, err := base64.StdEncoding.Decode(out[:], clean[:n])
	if err != nil {
		return nil
	}
	return out[:m]
}

// SniffImageMediaType inspects the leading bytes of a base64-encoded image and returns its MIME
// type. It recognises PNG, JPEG, GIF, WebP and SVG (so an unlabelled SVG can be rejected), and
// falls back to image/png when the header is unrecognised.
func SniffImageMediaType(b64 string) string {
	head := decodeBase64Prefix(b64)
	switch {
	case bytes.HasPrefix(head, []byte{0x89, 'P', 'N', 'G', '\r', '\n', 0x1a, '\n'}):
		return "image/png"
	case len(head) >= 3 && head[0] == 0xff && head[1] == 0xd8 && head[2] == 0xff:
		return "image/jpeg"
	case bytes.HasPrefix(head, []byte("GIF87a")) || bytes.HasPrefix(head, []byte("GIF89a")):
		return "image/gif"
	case len(head) >= 12 && bytes.Equal(head[0:4], []byte("RIFF")) && bytes.Equal(head[8:12], []byte("WEBP")):
		return "image/webp"
	default:
		trimmed := bytes.TrimLeft(head, " \t\r\n")
		if bytes.HasPrefix(bytes.ToLower(trimmed), []byte("<svg")) || bytes.HasPrefix(bytes.ToLower(trimmed), []byte("<?xml")) {
			return "image/svg+xml"
		}
		return "image/png"
	}
}

// SniffAudioMediaType inspects the leading bytes of a base64-encoded audio clip and returns its
// MIME type (WAV, MP3, FLAC, OGG), falling back to defaultType when unrecognised (such as raw
// PCM16).
func SniffAudioMediaType(b64, defaultType string) string {
	head := decodeBase64Prefix(b64)
	switch {
	case len(head) >= 12 && bytes.Equal(head[0:4], []byte("RIFF")) && bytes.Equal(head[8:12], []byte("WAVE")):
		return "audio/wav"
	case bytes.HasPrefix(head, []byte("ID3")) || (len(head) >= 2 && head[0] == 0xff && (head[1]&0xe0) == 0xe0):
		return "audio/mpeg"
	case bytes.HasPrefix(head, []byte("fLaC")):
		return "audio/flac"
	case bytes.HasPrefix(head, []byte("OggS")):
		return "audio/ogg"
	default:
		return defaultType
	}
}
